"""A dataset derived from TPC-H, generated by DuckDB's `dbgen`."""

import duckdb

from benchmarks.datasets.dataset import DatasetDefinition, declare_primary_keys
from benchmarks.datasets.schema import PrimaryKey
from benchmarks.datasets.dataset_types import References, Reference

SCALE_FACTOR = 0.01
# DuckDB's `dbgen` tables carry no key metadata, so the primary keys and the
# foreign-key swizzle mapping the FDM build needs are declared here.
TPCH_PRIMARY_KEYS: dict[str, PrimaryKey] = {
    "region": PrimaryKey.of("r_regionkey"),
    "nation": PrimaryKey.of("n_nationkey"),
    "supplier": PrimaryKey.of("s_suppkey"),
    "customer": PrimaryKey.of("c_custkey"),
    "part": PrimaryKey.of("p_partkey"),
    "partsupp": PrimaryKey.of(("ps_partkey", "ps_suppkey")),
    "orders": PrimaryKey.of("o_orderkey"),
    "lineitem": PrimaryKey.of(("l_orderkey", "l_linenumber")),
}
TPCH_REFERENCES: References = {
    "nation": {"n_regionkey": Reference("n_regionkey", "region")},
    "supplier": {"s_nationkey": Reference("s_nationkey", "nation")},
    "customer": {"c_nationkey": Reference("c_nationkey", "nation")},
    "partsupp": {
        "ps_partkey": Reference("ps_partkey", "part"),
        "ps_suppkey": Reference("ps_suppkey", "supplier"),
    },
    "orders": {"o_custkey": Reference("o_custkey", "customer")},
    "lineitem": {
        "l_orderkey": Reference("l_orderkey", "orders"),
        "l_partkey": Reference("l_partkey", "part"),
        "l_suppkey": Reference("l_suppkey", "supplier"),
    },
}


def build_tpch_connection(
    config: dict[str, str] | None = None,
) -> duckdb.DuckDBPyConnection:
    """A fresh TPC-H instance at `SCALE_FACTOR`, with the keys declared that the FDM
    stores the rows under, so DuckDB rejects a duplicate key (the FDM overwrites
    the tuple under it). `config` holds DuckDB settings for
    the connection, such as `extension_directory`. Raises `duckdb.IOException`
    when the `tpch` extension is not installed and cannot be downloaded; the
    connection is closed then."""
    connection = duckdb.connect(config=config or {})
    try:
        # installed explicitly: a failed automatic install would raise a bare
        # duckdb.Error instead of an IOException
        connection.execute("INSTALL tpch")
        connection.execute("LOAD tpch")
        connection.execute(f"CALL dbgen(sf={SCALE_FACTOR})")
        declare_primary_keys(connection, TPCH_PRIMARY_KEYS)
    except Exception:
        connection.close()
        raise
    return connection


TPCH = DatasetDefinition(
    name="tpch",
    references=TPCH_REFERENCES,
    primary_keys=TPCH_PRIMARY_KEYS,
    build_connection=build_tpch_connection,
)
